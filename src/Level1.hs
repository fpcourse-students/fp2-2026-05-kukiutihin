-- Простой язык выражений.
class Expr target where
  c :: Int -> target
  (.+) :: target -> target -> target
  (.*) :: target -> target -> target
  (.<) :: target -> target -> target

infixl 6 .+
infixl 7 .*
infix 4 .<

-- Пример программы в новом языке.
expr1 :: Expr target => target
expr1 = c 3 .* c 2 .+ c 42

-- Зададим реализацию для домена целых чисел.
instance Expr Int where
  c = id
  (.+) = (+)
  (.*) = (*)
  x .< y = if x < y then 1 else 0

